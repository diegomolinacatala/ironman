export interface RaceInput {
  name: string;
  date: ISODate | null;
  distance: RaceDistance;
  priority: RacePriority;
}

export interface OnboardingState {
  displayName: string;
  username: string;
  sports: TrainableSport[];
  level: AthleteLevel;
  availability: Availability;
  thresholds: ThresholdInputs;
  race: RaceInput;
}

export const EMPTY_RACE: RaceInput = { name: '', date: null, distance: 'olympic', priority: 'A' };

/** Usernames auto-generated by the sign-up trigger ("u" + 8 hex chars). */
export function isGeneratedUsername(username: string | null | undefined): boolean {
  return /^u[0-9a-f]{8}$/.test(username ?? '');
}

export function initialOnboardingState(profile: Profile | null | undefined): OnboardingState {
  const displayName = profile?.displayName ?? '';
  const username = profile?.username ?? '';
  return {
    displayName,
    username: isGeneratedUsername(username) ? suggestUsername(displayName) : username,
    sports: profile?.sports?.length ? profile.sports : ['swim', 'bike', 'run'],
    level: profile?.level ?? 'intermediate',
    availability: profile ? normalizeAvailability(profile.availability) : DEFAULT_AVAILABILITY,
    thresholds: profile ? thresholdsToInputs(profile.thresholds) : EMPTY_THRESHOLD_INPUTS,
    race: EMPTY_RACE,
  };
}

/** Inputs computed by the screen (async username check, zod messages). */
export interface StepChecks {
  usernameError: string | null;
  /** undefined while checking / unknown. */
  usernameAvailable: boolean | undefined;
  raceError: string | null;
}

export function stepIndex(id: OnboardingStepId): number {
  return ONBOARDING_STEPS.findIndex((s) => s.id === id);
}

/** Whether "Siguiente" is enabled for the given step. */
export function canAdvance(step: OnboardingStepId, state: OnboardingState, checks: StepChecks): boolean {
  switch (step) {
    case 'identity': {
      const name = state.displayName.trim();
      return name.length >= 1 && name.length <= 60 && !checks.usernameError && checks.usernameAvailable !== false;
    }
    case 'sports':
      return state.sports.length > 0;
    case 'availability':
      return state.availability.weeklyHoursTarget > 0;
    case 'thresholds':
      return parseThresholdInputs(state.thresholds).isValid;
    case 'race':
      return !hasRaceInput(state.race) || !checks.raceError;
    default:
      return true;
  }
}

export function hasRaceInput(race: RaceInput): boolean {
  return race.name.trim().length > 0 || race.date !== null;
}

/** RaceDraft when the user filled the (optional) race step, otherwise null. */
export function raceDraftFromInput(race: RaceInput): RaceDraft | null {
  if (!hasRaceInput(race) || !race.date) return null;
  return { name: race.name.trim(), date: race.date, distance: race.distance, priority: race.priority };
}

export function buildProfilePatch(
  state: OnboardingState,
  now: ISODateTime,
  baseThresholds: Thresholds = {},
): ProfilePatch {
  return {
    displayName: state.displayName.trim(),
    username: state.username,
    sports: state.sports,
    level: state.level,
    availability: state.availability,
    thresholds: parseThresholdInputs(state.thresholds, baseThresholds).thresholds,
    onboardedAt: now,
  };
}

export function toggleSport(sports: readonly TrainableSport[], sport: TrainableSport): TrainableSport[] {
  return sports.includes(sport) ? sports.filter((s) => s !== sport) : [...sports, sport];
}
